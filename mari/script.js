let numero1 = Number(prompt("digite o primeiro numero"))
let numero2 = Number(prompt("digite o segundo numero"))
let operacão = prompt ("informe a operacão: \n[+]\n[-]\n[*]\n[/]")


if(operacão == "+"){
    alert(numero1+numero2)
}
else if(operacão == "-"){
    alert(numero1-numero2)
}
else if(operacão == "*"){
    alert(numero1*numero2)
}

else if(operacão == "/"){
    alert(numero1/numero2)
}
